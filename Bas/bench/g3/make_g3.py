def main():
    words, labels = assemble(os.path.join(HERE, "kernels.vma"))
    while len(words) % 4:
        words.append(0)
    packed = [words[i] | words[i + 1] << 16 | words[i + 2] << 32 | words[i + 3] << 48 for i in range(0, len(words), 4)]
    params = {"NC": len(packed) - 1, "E1": labels["main1"], "E2": labels["main2"], "E3": labels["main3"],
              "E4": labels["main4"], "N1": 20000, "N2": 300, "JW": 40, "JH": 30, "N4": 4000}
    print("wordcode: %d words, entries %s" % (len(words), {k: labels[k] for k in ("main1", "main2", "main3", "main4")}))
    for cpu in ("m0", "m33"):
        text = BASIC
        for k, v in params.items():
            text = text.replace("@%s@" % k, str(v))
        out = text.splitlines()
        out.append("' leap seconds (solar_eclipse.bas)")
        for jd, ls in LEAP:
            out.append("Data %s, %s" % (jd, ls))
        out.append("' wordcode, four 16-bit words to an integer")
        for i in range(0, len(packed), 6):
            out.append("Data " + ", ".join("&H%X" % v for v in packed[i:i + 6]))
        out += csub(os.path.join(HERE, "vm_%s.txt" % cpu), "CSub VMRUN integer, integer, integer, integer, float, integer, integer")
        out += csub(os.path.join(HERE, "native_%s.txt" % cpu), "CSub NATIVE integer, integer, float, integer, integer")
        open(os.path.join(HERE, "g3_%s.bas" % cpu), "w", newline="\n").write("\n".join(out) + "\n")
        print("wrote g3_%s.bas" % cpu)


if __name__ == "__main__":
    main()
